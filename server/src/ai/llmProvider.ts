import { FAILURE_CLASSIFICATIONS, type AIClassification, type ModelInfo } from '../domain/types';
import { HeuristicProvider } from './heuristicProvider';
import type { AIProvider, DecisionExplanationInput, FailureAnalysisInput, ValidationAssessmentInput } from './provider';

export interface LlmConfig {
  provider: 'openai' | 'anthropic';
  apiKey: string;
  model: string;
  baseUrl?: string;
  timeoutMs?: number;
}

const SYSTEM_PROMPT = `You are a senior QA triage engineer. Classify automation test failures using ONLY the evidence given.
Allowed classifications: ${FAILURE_CLASSIFICATIONS.join(', ')}.
A passing re-run alone is NOT proof that the original failure was false.
Respond with strict JSON: {"classification": string, "confidence": number 0-1, "rootCause": string, "reasoning": string[], "recommendedAction": string}`;

/**
 * LLM-backed provider (OpenAI-compatible or Anthropic). Uses the heuristic provider's result as an
 * additional signal and falls back to it whenever the LLM call fails or returns invalid output.
 */
export class LlmProvider implements AIProvider {
  readonly info: ModelInfo;
  private readonly fallback = new HeuristicProvider();

  constructor(private readonly cfg: LlmConfig) {
    this.info = { provider: cfg.provider, model: cfg.model, version: 'api' };
  }

  async classifyFailure(input: FailureAnalysisInput): Promise<AIClassification> {
    const baseline = await this.fallback.classifyFailure(input);
    return this.refine(baseline, {
      task: 'classify_failure',
      test: { key: input.testCaseKey, name: input.testName, component: input.component, steps: input.testCase?.steps },
      errorMessage: input.errorMessage,
      stackTrace: input.stackTrace?.slice(0, 2000),
      history: input.history,
      jira: input.jira && { key: input.jira.issue.key, summary: input.jira.issue.summary, status: input.jira.issue.status },
      heuristicBaseline: { classification: baseline.classification, confidence: baseline.confidence, signals: baseline.signals },
    });
  }

  async assessValidation(input: ValidationAssessmentInput): Promise<AIClassification> {
    const baseline = await this.fallback.assessValidation(input);
    if (input.validation.status === 'NOT_REQUIRED') return baseline;
    return this.refine(baseline, {
      task: 'assess_revalidation',
      originalError: input.failure.errorMessage,
      initialClassification: input.initial.classification,
      revalidation: {
        status: input.validation.status,
        attempts: input.validation.attempts.map((a) => ({ status: a.status, error: a.errorMessage, similarity: a.similarityToOriginal })),
      },
      heuristicBaseline: { classification: baseline.classification, confidence: baseline.confidence },
    });
  }

  async explainDecision(input: DecisionExplanationInput): Promise<string> {
    const baseline = await this.fallback.explainDecision(input);
    try {
      const text = await this.complete(
        'You write concise executive release-readiness summaries. Never change or contradict the given decision.',
        `Explain this release decision for C-level stakeholders in under 180 words. Decision data:\n${JSON.stringify({
          execution: input.execution,
          health: input.health,
          counts: input.categoryCounts,
          decision: input.decision,
        })}`,
      );
      return `${text.trim()}\n\n(Decision computed by policy ${input.decision.policy.name} v${input.decision.policy.version}; narrative generated by ${this.info.model}.)`;
    } catch {
      return baseline;
    }
  }

  private async refine(baseline: AIClassification, payload: unknown): Promise<AIClassification> {
    try {
      const raw = await this.complete(SYSTEM_PROMPT, JSON.stringify(payload));
      const json = JSON.parse(raw.slice(raw.indexOf('{'), raw.lastIndexOf('}') + 1)) as Partial<AIClassification>;
      if (!json.classification || !FAILURE_CLASSIFICATIONS.includes(json.classification)) throw new Error('invalid classification');
      return {
        classification: json.classification,
        confidence: Math.max(0, Math.min(1, Number(json.confidence ?? baseline.confidence))),
        rootCause: json.rootCause ?? baseline.rootCause,
        reasoning: Array.isArray(json.reasoning) ? json.reasoning.map(String) : baseline.reasoning,
        signals: baseline.signals,
        recommendedAction: json.recommendedAction ?? baseline.recommendedAction,
        analyzedBy: this.info,
        analyzedAt: new Date().toISOString(),
      };
    } catch (err) {
      return { ...baseline, reasoning: [...baseline.reasoning, `LLM unavailable, heuristic result used (${(err as Error).message}).`] };
    }
  }

  private async complete(system: string, user: string): Promise<string> {
    const controller = new AbortController();
    const timer = setTimeout(() => controller.abort(), this.cfg.timeoutMs ?? 30_000);
    try {
      if (this.cfg.provider === 'anthropic') {
        const res = await fetch(`${this.cfg.baseUrl ?? 'https://api.anthropic.com'}/v1/messages`, {
          method: 'POST',
          signal: controller.signal,
          headers: { 'content-type': 'application/json', 'x-api-key': this.cfg.apiKey, 'anthropic-version': '2023-06-01' },
          body: JSON.stringify({ model: this.cfg.model, max_tokens: 800, system, messages: [{ role: 'user', content: user }] }),
        });
        if (!res.ok) throw new Error(`Anthropic API ${res.status}`);
        const body = (await res.json()) as { content: Array<{ type: string; text?: string }> };
        return body.content.map((c) => c.text ?? '').join('');
      }
      const res = await fetch(`${this.cfg.baseUrl ?? 'https://api.openai.com/v1'}/chat/completions`, {
        method: 'POST',
        signal: controller.signal,
        headers: { 'content-type': 'application/json', authorization: `Bearer ${this.cfg.apiKey}` },
        body: JSON.stringify({
          model: this.cfg.model,
          temperature: 0,
          messages: [
            { role: 'system', content: system },
            { role: 'user', content: user },
          ],
        }),
      });
      if (!res.ok) throw new Error(`OpenAI API ${res.status}`);
      const body = (await res.json()) as { choices: Array<{ message: { content: string } }> };
      return body.choices[0]?.message.content ?? '';
    } finally {
      clearTimeout(timer);
    }
  }
}
